namespace MsfsUi.Core.Packaging;

/// <summary>Overall state of the package in Community.</summary>
public enum PackageStatusKind
{
    /// <summary>No <c>msfs-ui</c> folder in Community.</summary>
    NotInstalled,

    /// <summary>An <c>msfs-ui</c> folder without our state file: not ours, never touched.</summary>
    Foreign,

    /// <summary>Installed and identical to what the app would generate now.</summary>
    UpToDate,

    /// <summary>Installed, but generating again would change it (see the reasons).</summary>
    UpdateNeeded,
}

/// <summary>Why the installed package differs from what the app would generate now.</summary>
public enum UpdateReason
{
    /// <summary>The package was generated by MSFS-UI 0.3.0 (no mod and settings hashes).</summary>
    LegacyPackage,

    /// <summary>The sim's MasterPage changed since the package was generated: a sim update.</summary>
    SimUpdated,

    /// <summary>The package comes from another version of the app.</summary>
    AppVersionChanged,

    /// <summary>Same version, but a different mod module (development builds).</summary>
    ModChanged,

    /// <summary>The user's settings changed since the package was installed.</summary>
    SettingsChanged,
}

/// <summary>The package in Community compared with what the app would generate now.</summary>
/// <param name="Kind">Overall state.</param>
/// <param name="PackageFolder">Folder of the package in Community.</param>
/// <param name="Installed">State of the installed package, if it is ours.</param>
/// <param name="Reasons">Why an update is needed (empty unless <see cref="PackageStatusKind.UpdateNeeded"/>).</param>
/// <param name="Conflicts">Other Community packages that also replace the MasterPage (only one can win).</param>
/// <param name="SimRunning">Whether the sim is running.</param>
public sealed record PackageStatus(
    PackageStatusKind Kind,
    string PackageFolder,
    PackageState? Installed,
    IReadOnlyList<UpdateReason> Reasons,
    IReadOnlyList<string> Conflicts,
    bool SimRunning);

/// <summary>What the user has to do in the sim after an installation.</summary>
public enum NextStep
{
    /// <summary>Nothing: the sim is not running, it will load the package at start-up.</summary>
    None,

    /// <summary>Restart the sim: new package, or a new MasterPage (both are read only at start-up).</summary>
    RestartSim,

    /// <summary>Reload the mod in the running sim (hot reload): the sim re-reads package files on the fly.</summary>
    ReloadMod,
}

/// <summary>Result of an installation.</summary>
/// <param name="State">State of the installed package.</param>
/// <param name="PackageFolder">Folder of the package in Community.</param>
/// <param name="FirstInstall">The package was not installed before.</param>
/// <param name="MasterPageChanged">The installed MasterPage differs from the previous one (loader or sim update).</param>
/// <param name="Conflicts">Other Community packages that also replace the MasterPage.</param>
/// <param name="NextStep">What the user has to do in the sim.</param>
public sealed record InstallResult(
    PackageState State,
    string PackageFolder,
    bool FirstInstall,
    bool MasterPageChanged,
    IReadOnlyList<string> Conflicts,
    NextStep NextStep);
