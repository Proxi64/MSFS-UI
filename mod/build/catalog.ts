// The feature catalogue (features.json) as seen by the build: consistency rules the JSON schema cannot express, and
// the TypeScript module generated from it (src/generated/catalog.ts), which gives the mod its typed settings.

import { constrain } from '../src/core/settings.ts';

export interface BooleanOptionJson {
  id: string;
  type: 'boolean';
  title: string;
  description: string;
  default: boolean;
}

export interface NumberOptionJson {
  id: string;
  type: 'number';
  title: string;
  description: string;
  default: number;
  min: number;
  max: number;
  step?: number;
  unit?: string;
}

export type OptionJson = BooleanOptionJson | NumberOptionJson;

export interface FeatureJson {
  id: string;
  title: string;
  description: string;
  screen: string;
  enabledByDefault: boolean;
  options: OptionJson[];
}

export interface CatalogJson {
  schemaVersion: 1;
  modVersion: string;
  features: FeatureJson[];
}

/** Rules beyond the schema (same as MsfsUi.Core FeatureCatalog.Validate): unique ids, defaults on the step grid. */
export function checkCatalog(catalog: CatalogJson): string[] {
  const errors: string[] = [];
  const duplicates = (ids: string[]) => ids.filter((id, at) => ids.indexOf(id) !== at);
  for (const id of duplicates(catalog.features.map((feature) => feature.id))) errors.push(`features.json: feature "${id}" is listed twice`);
  for (const feature of catalog.features) {
    for (const id of duplicates(feature.options.map((option) => option.id))) {
      errors.push(`features.json: option "${feature.id}.${id}" is listed twice`);
    }
    for (const option of feature.options) {
      if (option.type !== 'number') continue;
      const name = `features.json: option "${feature.id}.${option.id}"`;
      if (option.min > option.max) errors.push(`${name} has min > max`);
      else if (option.default < option.min || option.default > option.max) errors.push(`${name} has its default outside its range`);
      else if (Math.abs(constrain(option, option.default) - option.default) > 1e-9) errors.push(`${name} has its default off its step grid`);
    }
  }
  return errors;
}

/** `aircraftGallery` → `aircraft-gallery`: the file or folder name of a feature under src/features. */
export function kebabCase(id: string): string {
  return id.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/** The TypeScript module generated from the catalogue. */
export function generateCatalogModule(catalog: CatalogJson): string {
  const lines: string[] = [
    '// Generated by build/build.ts from features.json: do not edit.',
    '',
    "import type { FeatureSpec } from '../core/settings.ts';",
    '',
    `export const MOD_VERSION = ${JSON.stringify(catalog.modVersion)};`,
    '',
    '/** Settings of every feature, as read from config.js (see Contracts in docs/development.md). */',
    'export interface Settings {',
  ];
  for (const feature of catalog.features) {
    lines.push(`  /** ${comment(feature.title)} (${comment(feature.screen)}). */`, `  ${feature.id}: {`, '    enabled: boolean;');
    for (const option of feature.options) {
      const range = option.type === 'number' ? ` ${option.min} to ${option.max}${option.unit ? ` ${option.unit}` : ''}.` : '';
      lines.push(`    /** ${comment(option.title)}.${range} */`, `    ${option.id}: ${option.type};`);
    }
    lines.push('  };');
  }
  lines.push('}', '', 'export type FeatureId = keyof Settings;', '');
  lines.push(`export const FEATURE_IDS: readonly FeatureId[] = ${JSON.stringify(catalog.features.map((feature) => feature.id))};`, '');

  const specs = catalog.features.map((feature) => ({
    id: feature.id,
    enabledByDefault: feature.enabledByDefault,
    options: feature.options.map((option) =>
      option.type === 'boolean'
        ? { id: option.id, type: option.type, default: option.default }
        : { id: option.id, type: option.type, default: option.default, min: option.min, max: option.max, ...(option.step === undefined ? {} : { step: option.step }) },
    ),
  }));
  lines.push('/** What the mod checks config.js against. */', `export const CATALOG: readonly FeatureSpec[] = ${JSON.stringify(specs, null, 2)};`, '');
  return lines.join('\n');
}

function comment(text: string): string {
  return text.replace(/\*\//g, '* /');
}
